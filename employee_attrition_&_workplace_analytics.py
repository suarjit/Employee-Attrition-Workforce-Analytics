"""EXPECTED EDA: OUTLIER ANALYSIS USING IQR"""

outlier_cols = ["Age", "MonthlyIncome", "DistanceFromHome", "YearsAtCompany"]

outlier_results = []
for col in outlier_cols:
    q1 = df[col].quantile(0.25)
    q3 = df[col].quantile(0.75)
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    count = ((df[col] < lower) | (df[col] > upper)).sum()
    outlier_results.append({
        "Column": col,
        "Lower Bound": lower,
        "Upper Bound": upper,
        "Outlier Count": int(count)
    })

outlier_table = pd.DataFrame(outlier_results)
print("Outlier analysis using the IQR method:")
display(outlier_table.round(2))

for col in outlier_cols:
    plt.figure(figsize=(7, 4))
    sns.boxplot(x=df[col])
    plt.title(f"Outlier Check: {col}")
    plt.tight_layout()
    plt.show()

